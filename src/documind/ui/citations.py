"""Answer and source-evidence rendering.

Model output is rendered as Markdown with ``unsafe_allow_html=False`` (Streamlit's
default), so neither the model nor a document can inject HTML. Citation markers
``[S#]`` are renumbered 1..n in citation order and shown as native badges.
Evidence passages are inserted into our own markup only after HTML-escaping.
"""

from __future__ import annotations

import re
from html import escape

import streamlit as st

from documind.models import Citation, RAGAnswer
from documind.ui.theme import html, notice

_MARKER = re.compile(r"\s*\[(S\d+)\]")
INLINE_PASSAGES = 3


def numbering(answer: RAGAnswer) -> dict[str, int]:
    """Cited sources first (in citation order), then the remaining retrieved ones."""
    order = list(answer.cited_ids) + [s.source_id for s in answer.sources if s.source_id not in answer.cited_ids]
    return {sid: i for i, sid in enumerate(order, start=1)}


def answer_markdown(text: str, numbers: dict[str, int]) -> str:
    text = text.replace("$", r"\$")  # Streamlit treats $...$ as LaTeX

    def repl(match: re.Match[str]) -> str:
        n = numbers.get(match.group(1))
        return f" :primary-badge[{n}]" if n else ""

    return _MARKER.sub(repl, text)


def _source_block(src: Citation, n: int) -> str:
    chunk = src.chunk
    return (
        '<div class="dm-source">'
        f'<div class="dm-source-head"><span class="dm-num">{n}</span>'
        f'<span class="dm-file">{escape(chunk.filename)}</span>'
        f'<span class="dm-loc">{escape(chunk.location_label)}</span></div>'
        f'<div class="dm-quote">{escape(chunk.content)}</div>'
        f'<div class="dm-muted">Document text, chunk {chunk.chunk_index}, cosine similarity {src.similarity:.2f}</div>'
        "</div>"
    )


def _sources_html(sources: list[Citation], numbers: dict[str, int], cited: set[str]) -> str:
    ordered = sorted(sources, key=lambda s: numbers[s.source_id])  # list in citation-number order
    cited_blocks = [_source_block(s, numbers[s.source_id]) for s in ordered if s.source_id in cited]
    other = [s for s in ordered if s.source_id not in cited]
    parts = cited_blocks
    if other:
        if cited_blocks:
            parts.append('<div class="dm-group">Also retrieved, not cited in the answer</div>')
        parts.extend(_source_block(s, numbers[s.source_id]) for s in other)
    return "".join(parts)


def _footer(answer: RAGAnswer) -> str:
    bits = []
    if answer.provider and answer.model:
        bits.append(f"Generated by {answer.provider}, model {answer.model}")
    elif answer.model:
        bits.append(f"Generated by {answer.model}")
    if answer.latency_ms is not None:
        bits.append(f"{answer.latency_ms / 1000:.1f} s")
    if answer.usage and answer.usage.total_tokens:
        bits.append(f"{answer.usage.total_tokens:,} tokens")
    return f'<div class="dm-meta">{escape(", ".join(bits))}</div>' if bits else ""


def render_answer(answer: RAGAnswer, key: str) -> None:
    numbers = numbering(answer)
    cited = set(answer.cited_ids)
    with st.container(key=f"dm-answer-{key}"):
        if answer.mode == "generated":
            st.markdown(answer_markdown(answer.answer, numbers))
        elif answer.mode == "retrieval_only":
            notice(
                "Answer generation is off, so nothing was written for you. "
                "These are the most relevant passages from the selected documents.",
                "muted",
            )
        elif answer.mode == "no_results":
            st.markdown(answer_markdown(answer.answer, numbers))
            notice("No passage in the selected documents matched this question.", "warn")
        elif answer.mode == "no_documents":
            notice(answer.answer, "warn")
        else:  # error
            notice(answer.answer, "err")

        for warning in answer.warnings:
            notice(warning, "warn")

        if not answer.sources:
            return
        if answer.mode == "retrieval_only":
            # Evidence is the answer here: show the strongest passages, fold the rest.
            html(_sources_html(answer.sources[:INLINE_PASSAGES], numbers, cited=set()))
            rest = answer.sources[INLINE_PASSAGES:]
            if rest:
                with st.expander(f"More passages ({len(rest)})"):
                    html(_sources_html(rest, numbers, cited=set()))
            return
        label = f"Sources ({len(cited)})" if cited else f"Retrieved passages ({len(answer.sources)})"
        with st.expander(label, icon=":material/format_quote:"):
            html(_sources_html(answer.sources, numbers, cited) + _footer(answer))
